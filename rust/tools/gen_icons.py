"""Generates csdm-app/src/icons_data.rs from the 3.5 glyph set (electron/renderer/src/icons/index.tsx).

Each glyph is a list of filled SVG paths on a 24x24 grid; the app rasterises them once per size.
Usage (from rust/): python tools/gen_icons.py .. [--write]   (without --write: prints the file)
"""
import pathlib
import re
import sys

SOURCE = "electron/renderer/src/icons/index.tsx"
TARGET = "rust/csdm-app/src/icons_data.rs"


def parse(text: str) -> list[tuple[str, list[str]]]:
    bodies = {}
    for m in re.finditer(r"function (Icon\w+)\(\) \{(.*?)\n\}", text, re.S):
        bodies[m.group(1)] = re.findall(r'<path d="([^"]+)"', m.group(2))
    table = re.search(r"export const ICONS[^{]*\{(.*?)\};", text, re.S)
    if not table:
        sys.exit("ICONS table not found in " + SOURCE)
    out = []
    for name, fn in re.findall(r"(\w+): (Icon\w+),", table.group(1)):
        paths = bodies.get(fn)
        if not paths:
            sys.exit(f"{fn} has no path in {SOURCE}")
        out.append((name, paths))
    return out


def render(icons: list[tuple[str, list[str]]]) -> str:
    lines = [
        f"// @generated by rust/tools/gen_icons.py from {SOURCE}: do not edit, regenerate.",
        "//! The 3.5 glyph set: (name, filled SVG paths on a 24x24 grid).",
        "",
        "pub const ICONS: &[(&str, &[&str])] = &[",
    ]
    for name, paths in icons:
        joined = ", ".join(f'"{p}"' for p in paths)
        lines.append(f'    ("{name}", &[{joined}]),')
    lines.append("];")
    return "\n".join(lines) + "\n"


def main() -> None:
    root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "..")
    text = render(parse((root / SOURCE).read_text(encoding="utf-8")))
    if "--write" in sys.argv:
        (root / TARGET).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {TARGET}")
    else:
        print(text)


if __name__ == "__main__":
    main()
